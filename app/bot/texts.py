def get_text(key: str, **kwargs) -> str:
    """Текст из БД с подстановкой {placeholder} или дефолтный."""
    from app.db import db  # локальный импорт, чтобы избежать цикла

    raw = db.texts_cache.get(key)
    if not raw:
        raw = DEFAULT_TEXTS.get(key, key)
    try:
        return raw.format(**kwargs) if kwargs else raw
    except (KeyError, IndexError, ValueError):
        # в тексте остались незаменённые плейсхолдеры — подставим вручную
        out = raw
        for k, v in kwargs.items():
            out = out.replace("{" + str(k) + "}", str(v))
        return out